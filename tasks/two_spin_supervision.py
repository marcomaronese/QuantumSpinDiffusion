ROOT = Path(__file__).resolve().parents[1]
METRICS = ("trace_distance", "infidelity", "connected_correlation_error",
           "mutual_information_absolute_error", "marginal_trace_distance_mean")


def write_json(path: Path, value) -> None:
    path.write_text(json.dumps(value, indent=2, allow_nan=False) + "\n")


def interval(values) -> dict:
    values = np.asarray(values, dtype=float)
    mean = float(values.mean())
    half = (float(student_t.ppf(0.975, len(values) - 1) * values.std(ddof=1)
                  / np.sqrt(len(values))) if len(values) > 1 else None)
    return {"n": len(values), "mean": mean,
            "ci95": [mean - half, mean + half] if half is not None else None}


def summarize(rows: list[dict]) -> dict:
    """Validation selection only; repeated model conditions are paired by seed."""
    models = sorted({row["model"] for row in rows})
    means = {model: {key: interval([row["validation"][key] for row in rows
                                    if row["model"] == model]) for key in METRICS}
             for model in models}
    reference = {r["seed"]: r for r in rows if r["model"] == "path"}
    paired = {}
    eligible = []
    for mode in SUPERVISION_MODES:
        selected = [r for r in rows if r["model"] == mode]
        paired[mode] = {
            key: interval([r["validation"][key] - reference[r["seed"]]["validation"][key]
                           for r in selected]) for key in METRICS
        }
        physical = all(r["physicality_passed"] for r in selected)
        guardrails = physical and all(
            means[mode][key]["mean"] <= means["path"][key]["mean"] + margin
            for key, margin in [("infidelity", 0.005),
                                ("connected_correlation_error", 0.01),
                                ("marginal_trace_distance_mean", 0.01)]
        )
        if guardrails:
            eligible.append(mode)
    # Tie order was fixed in the protocol; no test information is used.
    winner = min(eligible, key=lambda mode: (
        means[mode]["trace_distance"]["mean"], SUPERVISION_MODES.index(mode)
    )) if eligible else None
    wins = (sum(r["validation"]["trace_distance"]
                <= reference[r["seed"]]["validation"]["trace_distance"]
                for r in rows if r["model"] == winner) if winner else 0)
    improvement = (means["path"]["trace_distance"]["mean"]
                   - means[winner]["trace_distance"]["mean"] if winner else 0)
    go = (winner is not None and winner != "path" and improvement >= 0.01
          and wins >= int(np.ceil(0.8 * len(reference))))
    return {
        "scope": "validation-only supervision screen; not independent confirmation",
        "models": means, "paired_minus_path": paired,
        "eligible": eligible, "validation_candidate": winner,
        "absolute_mean_trace_distance_improvement": improvement,
        "nonworse_seed_count": wins, "go_to_confirmation": go,
        "test_accessed": False,
        "intervals": "Descriptive paired Student-t 95% intervals; no multiplicity adjustment.",
        "next_action": ("Freeze a separate confirmation protocol before generating test data."
                        if go else "Diagnose budget/objective limits before any capacity change."),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--outdir", type=Path, default=ROOT / "outputs/experiments/two_spin_supervision_v1")
    parser.add_argument("--seeds", nargs="+", type=int, default=[67, 71, 73, 79, 83])
    parser.add_argument("--epochs", type=int, default=80)
    parser.add_argument("--n-data", type=int, default=1200)
    parser.add_argument("--baseline-epochs", type=int, default=300)
    parser.add_argument("--baseline-samples", type=int, default=2000)
    args = parser.parse_args()
    if min(args.epochs, args.n_data, args.baseline_epochs, args.baseline_samples) < 1:
        raise ValueError("budgets and sample counts must be positive")
    if args.n_data < 2 or len(set(args.seeds)) != len(args.seeds):
        raise ValueError("need at least two data points and distinct seeds")
    root = args.outdir.resolve()
    if not root.is_relative_to(ROOT / "outputs/experiments"):
        raise ValueError("study outputs must remain under outputs/experiments")
    root.mkdir(parents=True, exist_ok=False)
    torch.set_num_threads(1)
    torch.use_deterministic_algorithms(True)
    classical = ClassicalDiffusionConfig(epochs=args.baseline_epochs)
    protocol = {
        "version": "two_spin_supervision_v1", "seeds": args.seeds,
        "split_seed_offsets": {"train": 0, "validation": 10000,
                               "initialization": 20000, "closed_test": 30000},
        "n_train": args.n_data, "n_validation": args.n_data,
        "closed_test_samples_planned": 1200, "test_generated": False,
        "dataset": {"family": "rotated normalized-Gaussian directional pairs",
                    "sigma": 0.18, "rotation_angle": 0.55},
        "architecture": {"j": 1.0, "steps": 3, "layers": 1,
                         "shared_ancilla_count": 1, "direct_interactions": True,
                         "independent_time_parameters": True, "parameters": 39},
        "forward": {"D": 1.0, "dt": 0.5},
        "optimization": {"objective": "fidelity", "optimizer": "Adam",
                         "learning_rate": 0.04, "betas": [0.9, 0.999],
                         "epsilon": 1e-8, "updates": args.epochs,
                         "early_stopping": False, "restarts": 0,
                         "channel_evaluations_per_update": 3,
                         "stepwise": "average exact-input one-step losses; one joint update"},
        "conditions": list(SUPERVISION_MODES), "prior": "I_9/9 for assembled generation",
        "primary_metric": "validation trace distance to independently encoded validation density",
        "selection": {"guardrails_vs_path_mean": {"infidelity": 0.005,
                       "connected_correlation_error": 0.01,
                       "marginal_trace_distance_mean": 0.01},
                      "tie_order": list(SUPERVISION_MODES),
                      "minimum_absolute_trace_improvement": 0.01,
                      "minimum_nonworse_seed_fraction": 0.8,
                      "physicality_and_cptp_tolerance": 1e-10},
        "baseline_budgets": {"classical_ddpm": asdict(classical),
                             "neural_epochs": args.baseline_epochs,
                             "neural_parameters": 39, "neural_learning_rate": 0.03,
                             "heat_bandwidth": 0.1, "tensor_bond_dimension": 2,
                             "generated_samples": args.baseline_samples,
                             "seed_offsets": {"neural": 40000, "ddpm": 50000,
                                              "heat": 60000, "tensor": 70000,
                                              "neural_sampling": 80000}},
        "limits": ["One distribution family; validation selection is not confirmation.",
                   "Classical budgets and sampled-state errors are not matched to exact quantum states.",
                   "State metrics only; common physical POVM and sample MMD are deferred to E6.",
                   "Quantum mutual information is not source classical mutual information; the latter is not estimated.",
                   "Normalization does not by itself isolate gradient interference.",
                   "Direct interactions retained; no architecture redesign or factorized-channel ablation."],
    }
    protocol["protocol_sha256"] = hashlib.sha256(
        json.dumps(protocol, sort_keys=True).encode()).hexdigest()
    write_json(root / "protocol.json", protocol)
    sources = [ROOT / "pyproject.toml", ROOT / "notes/protocols/TWO_SPIN_SUPERVISION_V1.md"]
    for folder in ["src/spin_quantum_diffusion", "tasks"]:
        sources.extend(sorted((ROOT / folder).rglob("*.py")))
    hashes = {}
    for source in sources:
        relative = source.relative_to(ROOT)
        destination = root / "source" / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, destination)
        hashes[str(relative)] = hashlib.sha256(source.read_bytes()).hexdigest()
    write_json(root / "source_manifest.json", hashes)
    metadata = reproducibility_metadata(ExperimentConfig(), ROOT)
    # A multi-dataset study has no single run seed. Split/init roles live in
    # the frozen protocol; do not inherit the single-spin config's default 7.
    metadata.pop("seed", None)
    metadata["study_seeds"] = args.seeds
    metadata["protocol_sha256"] = protocol["protocol_sha256"]
    write_json(root / "reproducibility.json", metadata)
    jx, jy, jz, identity = toy.spin_operators(1.0)
    operators = [jx, jy, jz]
    generators, names = build_two_spin_reverse_generators(operators, identity, True)
    local_basis = irreducible_spherical_tensors(1.0, jx, jy)
    prior = torch.eye(9, dtype=toy.CDTYPE) / 9
    rows = []
    try:
        for seed in args.seeds:
            directory = root / f"seed_{seed}"
            directory.mkdir()
            train_pairs = make_correlated_direction_pairs(args.n_data, 0.18, 0.55, seed)
            val_pairs = make_correlated_direction_pairs(args.n_data, 0.18, 0.55, seed + 10000)
            targets = {"train": empirical_joint_density(train_pairs, 1.0),
                       "validation": empirical_joint_density(val_pairs, 1.0)}
            np.save(directory / "train_pairs.npy", np.asarray(train_pairs))
            np.save(directory / "validation_pairs.npy", np.asarray(val_pairs))
            forward = build_two_spin_forward_trajectory(targets["train"], operators, identity, 1.0, 0.5, 3)
            np.save(directory / "forward_states.npy", torch.stack(forward).numpy())
            for split, target in targets.items():
                toy.assert_physical_density(target, split)
                np.save(directory / f"rho_{split}.npy", target.numpy())
            coefficients = [joint_multipole_coefficients(state, local_basis) for state in forward]
            keys = list(coefficients[0])
            decay_error = max(float(abs(at_time[key] - coefficients[0][key] * np.exp(
                -(key[0] * (key[0] + 1) + key[2] * (key[2] + 1)) * step * 0.5)))
                for step, at_time in enumerate(coefficients) for key in keys)
            assert decay_error < 1e-10
            write_json(directory / "dataset_manifest.json", {
                "sha256": {p.name: hashlib.sha256(p.read_bytes()).hexdigest()
                           for p in sorted(directory.glob("*.npy"))},
                "forward_decay_error": decay_error, "test_generated": False,
            })

            def evaluate(model, density, training_seconds, generation_seconds,
                         parameters=0, physicality_passed=True):
                metrics = {}
                independent_delta = 0.0
                predicted = joint_multipole_coefficients(density, local_basis)
                for split, target in targets.items():
                    values = density_metrics(
                        density, target, quantum_mutual_information(target, 3),
                        connected_spin_correlation(target, operators, identity), operators, identity)
                    independent = independent_metrics(density.numpy(), target.numpy())
                    independent_delta = max(independent_delta, max(
                        abs(values[key] - independent[key]) for key in independent))
                    assert independent_delta < 2e-9
                    marginal_errors = [float(toy.trace_distance(
                        partial_trace_two_spin(density, 3, keep),
                        partial_trace_two_spin(target, 3, keep))) for keep in (0, 1)]
                    values["marginal_trace_distance_mean"] = float(np.mean(marginal_errors))
                    values["marginal_trace_distances"] = marginal_errors
                    target_coeffs = joint_multipole_coefficients(target, local_basis)
                    rank_errors = {}
                    for key in keys:
                        rank = f"{key[0]},{key[2]}"
                        rank_errors[rank] = rank_errors.get(rank, 0.0) + float(
                            abs(predicted[key] - target_coeffs[key]) ** 2)
                    assert abs(sum(rank_errors.values()) - values["frobenius_error"]) < 1e-12
                    values["multipole_rank_squared_errors"] = rank_errors
                    np.savez(directory / f"{model}_{split}_multipoles.npz",
                             keys=np.asarray(keys), predicted=np.asarray([complex(predicted[k]) for k in keys]),
                             target=np.asarray([complex(target_coeffs[k]) for k in keys]))
                    metrics[split] = values
                np.save(directory / f"{model}_rho.npy", density.numpy())
                row = {"seed": seed, "model": model, "trainable_parameters": parameters,
                       "training_seconds": training_seconds, "generation_seconds": generation_seconds,
                       "physicality_passed": physicality_passed,
                       "independent_metric_maximum_discrepancy": independent_delta, **metrics}
                rows.append(row)
                write_json(directory / f"{model}_metrics.json", row)
                return row

            torch.manual_seed(seed + 20000)
            initial = 0.03 * torch.randn(3, 1, len(generators), dtype=toy.RDTYPE)
            torch.save(initial, directory / "paired_initial_parameters.pt")
            for mode in SUPERVISION_MODES:
                diagnostics = []
                started = time.perf_counter()
                parameters, history = toy.train_reverse(
                    forward, generators, 1, args.epochs, 0.04, seed + 20000,
                    objective="fidelity", supervision=mode, training_diagnostics=diagnostics)
                training_seconds = time.perf_counter() - started
                started = time.perf_counter()
                trajectory = toy.generate_trajectory(prior, parameters, generators)
                generation_seconds = time.perf_counter() - started
                residuals = [toy.assert_physical_density(rho, mode) for rho in trajectory]
                completeness, minimum_choi = reverse_cptp_residuals(parameters, generators, 9, 3)
                assert completeness < 1e-10 and minimum_choi >= -1e-10
                np.save(directory / f"{mode}_reverse_states.npy", torch.stack(trajectory).numpy())
                torch.save(parameters, directory / f"{mode}_parameters.pt")
                write_json(directory / f"{mode}_training.json", {
                    "loss_history_before_updates": history, "diagnostics": diagnostics,
                    "generator_names": names, "optimizer_updates": args.epochs,
                    "channel_evaluations": args.epochs * 3, "state_residuals": residuals,
                    "kraus_completeness_error": completeness, "minimum_choi_eigenvalue": minimum_choi,
                })
                row = evaluate(mode, trajectory[-1], training_seconds, generation_seconds, parameters.numel())
                row["kraus_completeness_error"] = completeness
                row["minimum_choi_eigenvalue"] = minimum_choi
                print(f"seed={seed} mode={mode} validation_trace={row['validation']['trace_distance']:.6f}", flush=True)

            # Each baseline is fitted once per split, held fixed across all four conditions.
            started = time.perf_counter()
            state = factorized_density(targets["train"], 3)
            evaluate("factorized", state, 0.0, time.perf_counter() - started)
            started = time.perf_counter()
            state = clustered_product_mixture_density(train_pairs, 1.0, 2, seed + 70000)
            evaluate("tensor_mixture", state, time.perf_counter() - started, 0.0)
            started = time.perf_counter()
            heat_pairs = sample_riemannian_heat_kernel(train_pairs, args.baseline_samples, 0.1, seed + 60000)
            state = empirical_joint_density(heat_pairs, 1.0)
            evaluate("heat_kernel", state, 0.0, time.perf_counter() - started)
            np.save(directory / "heat_kernel_pairs.npy", np.asarray(heat_pairs))
            started = time.perf_counter()
            neural, history = train_neural_baseline(train_pairs, 39, args.baseline_epochs, seed + 40000)
            elapsed = time.perf_counter() - started
            torch.save(neural.state_dict(), directory / "neural_parameters.pt")
            write_json(directory / "neural_history.json", history)
            started = time.perf_counter()
            neural_pairs = sample_neural_pairs(neural, args.baseline_samples, seed + 80000)
            state = empirical_joint_density(neural_pairs, 1.0)
            evaluate("neural", state, elapsed, time.perf_counter() - started, 39)
            np.save(directory / "neural_pairs.npy", np.asarray(neural_pairs))
            ddpm_pairs, meta = run_classical_benchmark(
                train_pairs, classical, seed + 50000, args.baseline_samples, directory / "classical")
            state = empirical_joint_density(ddpm_pairs, 1.0)
            evaluate("classical_ddpm", state, meta["training_seconds"], meta["sampling_seconds"],
                     meta["trainable_parameter_count"])
            write_json(root / "results.json", rows)
        write_json(root / "selection.json", summarize(rows))
        write_json(root / "artifact_manifest.json", {
            str(p.relative_to(root)): hashlib.sha256(p.read_bytes()).hexdigest()
            for p in sorted(root.rglob("*")) if p.is_file()
        })
    except Exception as error:
        write_json(root / "failure.json", {"type": type(error).__name__, "message": str(error),
                                           "completed_rows": len(rows), "test_accessed": False})
        raise
    print(json.dumps(summarize(rows), indent=2), flush=True)


if __name__ == "__main__":
    main()
